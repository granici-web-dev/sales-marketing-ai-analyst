/**
 * Навигация портала: слева агенты, а не экраны.
 *
 * Здесь только типы и правила — ни одного обращения наружу. Список рисует
 * клиентский компонент, и модуль, который он импортирует, обязан собираться
 * в браузерный бандл. Запрос к движку живёт рядом, в `portal-nav.server.ts`:
 * он ходит через `next/headers`, а это на клиенте не существует. Разделение
 * не по вкусу, а по границе исполнения.
 *
 * ── Почему так ──
 *
 * Кабинет один на всех агентов. Человек думает не «пойду на страницу
 * маркетинга», а «посмотрю, что у аналитика». Список экранов вперемешку —
 * маркетинг, продажи, интеграции, настройки — читается как меню одного
 * приложения и разваливается на втором агенте: чьи это продажи, чей чат.
 *
 * Поэтому первый уровень — агенты, второй — вкладки внутри агента. Ровно
 * столько уровней, сколько есть в предметной области, и ни одного лишнего.
 *
 * ── Про аналитика ──
 *
 * Шесть агентов из семи заводит и продаёт движок, и он же отвечает, что
 * куплено. Аналитик — исключение, записанное в его собственном манифесте:
 * «НЕ РЕАЛИЗОВАНО В ЭТОМ ДВИЖКЕ… отдельный продукт со своим кабинетом и
 * своей подпиской». Этот кабинет и есть его кабинет: спрашивать движок,
 * открыт ли аналитик, значит спрашивать не того.
 */
import type { AgentAccess, UnlockPlan } from "@/lib/portal-agents";

/** Агент, чей кабинет это и есть. Его экраны живут здесь, а не в движке. */
export const HOST_AGENT = "data-analyst";

/** Первая вкладка аналитика — она же адрес самого агента. */
export const HOST_AGENT_HREF = "/marketing";

export interface NavAgent {
  id: string;
  access: AgentAccess;
  /** Куда ведёт пункт. Заперт — ведёт на свою страницу с предложением включить. */
  href: string;
  daysLeft: number | null;
  priceFrom: number | null;
  /** Чем включить. null — покупаемого тарифа с ним нет. */
  plan: UnlockPlan | null;
}

export interface PortalAccount {
  email: string;
  tenantName: string | null;
}

export interface PortalNav {
  agents: NavAgent[];
  /** Кто вошёл. null — не вошли: внизу вместо учётной записи стоит вход. */
  account: PortalAccount | null;
  /**
   * Знаем ли мы, что куплено.
   *
   * `false` — в движок не вошли. Тогда слева остаётся один аналитик: его
   * экраны работают на своём входе и закрывать их из-за чужой учётной записи
   * было бы наказанием ни за что.
   */
  linked: boolean;
}

export const HOST_AGENT_NAV: NavAgent = {
  id: HOST_AGENT,
  access: "unlocked",
  href: HOST_AGENT_HREF,
  daysLeft: null,
  priceFrom: null,
  plan: null,
};

/** Заперт ли раздел: и «можно купить», и «ещё не построен» одинаково закрыты. */
export const isLocked = (access: AgentAccess): boolean =>
  access === "locked" || access === "unavailable";
