/**
 * Шов к движку — единственное место, где кабинет знает о его существовании.
 *
 * ── Кто кому удостоверяет личность ──
 *
 * Движок. Не потому, что так сложилось, а потому, что его вход строже по
 * каждому пункту: непрозрачный токен вместо JWT, хеш токена в базе вместо
 * самого токена, серверная сессия, которую можно отозвать, печенье с
 * HttpOnly и SameSite=Strict, сравнение пароля постоянного времени. И
 * потому, что он уже владеет тем, что решает доступ, — арендаторами,
 * тарифами, таблицей `tenant_agents` и оплатой. Аналитик здесь один агент
 * из семи; сделать его хозяином личности для остальных шести значило бы
 * перевернуть подчинение.
 *
 * ── Почему браузер не ходит в движок сам ──
 *
 * Печенье сессии принадлежит домену, который его поставил. Пустить браузер
 * напрямую значило бы либо расширять область печенья до общего домена
 * второго уровня — то есть привязать себя к одной схеме размещения, — либо
 * ослаблять SameSite. Вместо этого кабинет работает доверенным посредником:
 * печенье живёт на его домене, а к движку он ходит сам, со стороны сервера.
 * Ни одно из свойств печенья при этом не теряется.
 */
import { cookies } from "next/headers";

/** Имя печенья движка. Оно же используется у нас — значение то же самое. */
export const ENGINE_SESSION_COOKIE = "aw_session";

export function engineBaseUrl(): string {
  const url = process.env.ENGINE_BASE_URL;
  if (!url) {
    // Та же позиция, что с JWT_SECRET_KEY: незаданная настройка — это поломка
    // настройки, и вести себя как «нет доступа» она не должна.
    throw new Error(
      "ENGINE_BASE_URL не задан — спросить движок о правах невозможно. " +
        "Смотрите frontend/.env.example.",
    );
  }
  return url.replace(/\/+$/, "");
}

/**
 * `unauthenticated` — это ответ, а не сбой: человек просто не вошёл.
 *
 * Всё остальное — исключение. Молчаливо превращать недоступный движок в
 * пустой список значило бы показать человеку, что у него нет ни одного
 * агента, тогда как на самом деле мы не смогли спросить. Замок, которого
 * нет, хуже ошибки, которая есть.
 */
export type EngineResult<T> =
  | { ok: true; data: T }
  | { ok: false; reason: "unauthenticated" };

export async function engineGet<T>(path: string): Promise<EngineResult<T>> {
  const token = (await cookies()).get(ENGINE_SESSION_COOKIE)?.value;
  if (!token) return { ok: false, reason: "unauthenticated" };

  const response = await fetch(`${engineBaseUrl()}${path}`, {
    headers: { cookie: `${ENGINE_SESSION_COOKIE}=${token}` },
    // Права — это то, что меняется оплатой. Кешированный ответ показывал бы
    // замок на агенте, за которого уже заплатили.
    cache: "no-store",
  });

  if (response.status === 401) return { ok: false, reason: "unauthenticated" };
  if (!response.ok) {
    throw new Error(`Движок ответил ${response.status} на ${path}`);
  }
  return { ok: true, data: (await response.json()) as T };
}
